// Turns content/courses/*.json into a migration (courses, lessons, public steps and server-only keys).
// Run after editing lessons (npm test checks and executes them first): npm run gen:lessons
// Writes nothing when a course file is unchanged since its last generated migration.
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const root = new URL('..', import.meta.url)
const dir = new URL('content/courses/', root)
const migrations = new URL('supabase/migrations/', root)

const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replaceAll("'", "''")}'`)
const j = (v) => (v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`)
const arr = (xs) => (xs ? `array[${xs.map(q).join(',')}]::text[]` : 'null')
const SORT = { 'python-basics': 10, 'javascript-basics': 20, 'data-structures': 21, 'ai-basics': 22, 'machine-learning': 23, 'cpp-basics': 24, 'english-basics': 30, 'malay-basics': 40, 'arabic-basics': 50, 'japanese-basics': 60, 'korean-basics': 70, 'mandarin-basics': 80 }

// A fixed shuffle per step, so match lists and build tiles never show the answer order and never change between runs.
function shuffled(xs, seed) {
  let h = 0
  for (const ch of seed) h = (h * 31 + ch.charCodeAt(0)) >>> 0
  const out = [...xs]
  for (let i = out.length - 1; i > 0; i--) {
    h = (h * 1103515245 + 12345) >>> 0
    const k = h % (i + 1)
    ;[out[i], out[k]] = [out[k], out[i]]
  }
  return out
}

for (const file of readdirSync(dir).filter((f) => f.endsWith('.json'))) {
  const raw = readFileSync(new URL(file, dir), 'utf8')
  const course = JSON.parse(raw)
  const hash = createHash('sha256').update(raw).digest('hex').slice(0, 12)
  const previous = readdirSync(migrations).filter((f) => f.endsWith(`_lessons_${course.id}.sql`)).sort().at(-1)
  if (previous && readFileSync(new URL(previous, migrations), 'utf8').includes(`content-hash: ${hash}`)) {
    console.log(`${course.id}: unchanged (${previous})`)
    continue
  }
  const lessons = []
  const steps = []
  const keys = []
  course.units.forEach((u, ui) =>
    u.lessons.forEach((l, li) => {
      lessons.push(`  (${[q(l.id), q(course.id), ui + 1, q(u.title), li + 1, q(l.title), q(l.objective), q(l.status), l.version, q(course._meta.author), q(course._meta.license)].join(', ')})`)
      l.steps.forEach((s, si) => {
        const code = s.kind === 'write' ? null : (s.code ?? null)
        const pairs = s.pairs ? { left: shuffled(s.pairs.map((x) => x[0]), `${s.id}L`), right: shuffled(s.pairs.map((x) => x[1]), `${s.id}R`) } : null
        const tiles = s.tiles ? shuffled(s.tiles, s.id) : null
        steps.push(`  (${[q(s.id), q(l.id), si + 1, q(s.kind), q(s.text), q(code), j(s.options ?? null), s.broken_line ?? 'null', q(s.starter ?? null), q(s.expected_output ?? null), arr(s.must_use), q(s.hint ?? null), q(s.word ?? null), q(s.meaning ?? null), q(s.emoji ?? null), q(s.say ?? null), q(s.prompt ?? null), q(s.note ?? null), q(s.sentence ?? null), arr(tiles), j(pairs)].join(', ')})`)
        const answer =
          s.kind === 'fix' || s.kind === 'type' ? { accept: s.accept }
          : s.kind === 'predict' ? (s.answer !== undefined ? { choice: s.answer } : { text: s.answer_text })
          : s.kind === 'pick' || s.kind === 'gap' || s.kind === 'listen' ? { choice: s.answer }
          : s.kind === 'match' ? { pairs: s.pairs }
          : s.kind === 'build' ? { orders: [s.answer, ...(s.accept_orders ?? [])] }
          : null
        keys.push(`  (${[q(s.id), j(answer), q(s.explanation ?? null), q(s.solution ?? null)].join(', ')})`)
      })
    }),
  )
  const allLessons = course.units.flatMap((u) => u.lessons.map((l) => l.id))
  const allSteps = course.units.flatMap((u) => u.lessons.flatMap((l) => l.steps.map((s) => s.id)))
  const latest = readdirSync(migrations).map((f) => f.split('_')[0]).filter((s) => /^\d{14}$/.test(s)).sort().at(-1) ?? '0'
  const now = new Date().toISOString().replace(/\D/g, '').slice(0, 14)
  const stamp = now > latest ? now : String(BigInt(latest) + 1n)
  const sql = `-- GENERATED by scripts/gen-lessons.mjs from content/courses/${file}. Do not edit by hand.
-- content-hash: ${hash}
insert into public.courses (id, kind, language, title, sort) values (${q(course.id)}, ${q(course.kind)}, ${q(course.language)}, ${q(course.title)}, ${SORT[course.id] ?? 99})
on conflict (id) do update set kind = excluded.kind, language = excluded.language, title = excluded.title, sort = excluded.sort;

-- Review status belongs to the database (review_lesson); a higher version sends a lesson back for review.
insert into public.lessons (id, course_id, unit_index, unit_title, lesson_index, title, objective, status, version, source_name, license) values
${lessons.join(',\n')}
on conflict (id) do update set
  course_id = excluded.course_id, unit_index = excluded.unit_index, unit_title = excluded.unit_title, lesson_index = excluded.lesson_index,
  title = excluded.title, objective = excluded.objective, status = 'in_review', version = excluded.version,
  source_name = excluded.source_name, license = excluded.license
where public.lessons.version < excluded.version;

delete from public.lesson_steps where lesson_id in (${allLessons.map(q).join(', ')}) and id <> all (array[${allSteps.map(q).join(', ')}]::text[]);
insert into public.lesson_steps (id, lesson_id, step_index, kind, text, code, options, broken_line, starter, expected_output, must_use, hint, word, meaning, emoji, say, prompt, note, sentence, tiles, pairs) values
${steps.join(',\n')}
on conflict (id) do update set lesson_id = excluded.lesson_id, step_index = excluded.step_index, kind = excluded.kind, text = excluded.text,
  code = excluded.code, options = excluded.options, broken_line = excluded.broken_line, starter = excluded.starter,
  expected_output = excluded.expected_output, must_use = excluded.must_use, hint = excluded.hint, word = excluded.word, meaning = excluded.meaning,
  emoji = excluded.emoji, say = excluded.say, prompt = excluded.prompt, note = excluded.note, sentence = excluded.sentence, tiles = excluded.tiles, pairs = excluded.pairs;

insert into public.lesson_step_keys (step_id, answer, explanation, solution) values
${keys.join(',\n')}
on conflict (step_id) do update set answer = excluded.answer, explanation = excluded.explanation, solution = excluded.solution;
`
  const out = `${stamp}_lessons_${course.id}.sql`
  writeFileSync(new URL(out, migrations), sql)
  console.log(`${course.id}: ${lessons.length} lessons -> supabase/migrations/${out}`)
}
