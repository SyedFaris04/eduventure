"""Writes supabase/migrations/20261121090001_blocked_words.sql from content/blocked-words.txt.

Run after editing the word list, then push the migration. Words are only ever added here
(removing one later needs a delete in a new migration)."""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
words = []
for line in (root / 'content' / 'blocked-words.txt').read_text(encoding='utf8').splitlines():
    w = line.strip()
    if not w or w.startswith('#'):
        continue
    assert re.fullmatch(r'[a-z]+', w), f'only lower-case letters: {w!r}'
    if w not in words:
        words.append(w)

out = root / 'supabase' / 'migrations' / '20261121090001_blocked_words.sql'
values = ',\n  '.join(f"('{w}')" for w in words)
out.write_text(
    '-- Generated by scripts/gen-blocked-words.py from content/blocked-words.txt. Do not edit by hand.\n'
    f'insert into public.blocked_words (word) values\n  {values}\non conflict do nothing;\n',
    encoding='utf8', newline='\n')
print(f'{len(words)} words -> {out.name}')
