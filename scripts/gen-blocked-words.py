"""Writes a new migration that makes public.blocked_words match content/blocked-words.txt exactly.

Each run writes a NEW file, timestamped one second after the latest migration, because migrations are never
edited once pushed. Lines starting with = are whole-word entries. Run after editing the list, then push."""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
words = {}
for line in (root / 'content' / 'blocked-words.txt').read_text(encoding='utf8').splitlines():
    w = line.strip()
    if not w or w.startswith('#'):
        continue
    whole = w.startswith('=')
    w = w.lstrip('=')
    assert re.fullmatch(r'[a-z]+', w), f'only lower-case letters: {w!r}'
    words[w] = whole

migrations = root / 'supabase' / 'migrations'
latest = max(int(p.name[:14]) for p in migrations.glob('*.sql'))
stamp = str(latest + 1)
out = migrations / f'{stamp}_blocked_words.sql'
values = ',\n  '.join(f"('{w}', {'true' if whole else 'false'})" for w, whole in words.items())
quoted = ', '.join(f"'{w}'" for w in words)
out.write_text(
    '-- Generated by scripts/gen-blocked-words.py from content/blocked-words.txt. Do not edit by hand.\n'
    f'insert into public.blocked_words (word, whole_word) values\n  {values}\n'
    'on conflict (word) do update set whole_word = excluded.whole_word;\n'
    f'delete from public.blocked_words where word not in ({quoted});\n',
    encoding='utf8', newline='\n')
print(f'{len(words)} words ({sum(words.values())} whole-word) -> {out.name}')
