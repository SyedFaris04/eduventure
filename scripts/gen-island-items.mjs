// Writes a migration that makes the database's island catalogue and its level unlocks match
// content/island-items.json (the client imports the same file). Run after editing it, then push.
// Each run writes a new migration, one second after the latest, so a live migration is never edited.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const { items } = JSON.parse(readFileSync('content/island-items.json', 'utf8'))
const CATEGORIES = ['house', 'garden', 'trees', 'paths', 'lights', 'furniture', 'malaysian', 'water']
const MATERIALS = ['wood', 'stone', 'herbs', 'crystal']
const ids = new Set()
for (const it of items) {
  if (!/^[a-z][a-z0-9_]*$/.test(it.id) || ids.has(it.id)) throw new Error(`bad or repeated id: ${it.id}`)
  ids.add(it.id)
  if (!CATEGORIES.includes(it.category)) throw new Error(`${it.id}: unknown category ${it.category}`)
  if (!Object.keys(it.cost).length || Object.entries(it.cost).some(([m, n]) => !MATERIALS.includes(m) || !(Number.isInteger(n) && n > 0)))
    throw new Error(`${it.id}: bad cost`)
  for (const k of ['level', 'w', 'h']) if (!(Number.isInteger(it[k]) && it[k] >= 1)) throw new Error(`${it.id}: bad ${k}`)
  if (typeof it.blocks !== 'boolean') throw new Error(`${it.id}: blocks must be true or false`)
}

const q = (s) => `'${s.replace(/'/g, "''")}'`
const rows = items.map((it, i) => `  (${q(it.id)}, ${q(it.category)}, ${q(JSON.stringify(it.cost))}, ${it.w}, ${it.h}, ${it.blocks}, ${(i + 1) * 10})`)
const locked = items.filter((it) => it.level > 1)
const sql = `-- Generated by scripts/gen-island-items.mjs from content/island-items.json. Do not edit; edit the JSON and run it again.
insert into public.island_catalog (id, category, cost, w, h, blocks, sort) values
${rows.join(',\n')}
on conflict (id) do update set category = excluded.category, cost = excluded.cost, w = excluded.w, h = excluded.h,
  blocks = excluded.blocks, sort = excluded.sort;
delete from public.island_catalog where id not in (${items.map((it) => q(it.id)).join(', ')})
  and not exists (select 1 from public.island_items i where i.item = island_catalog.id);

delete from public.level_unlocks where kind = 'island_item';
${locked.length ? `insert into public.level_unlocks (level, kind, key) values\n${locked.map((it) => `  (${it.level}, 'island_item', ${q(it.id)})`).join(',\n')};\n` : ''}`

const dir = 'supabase/migrations'
const latest = readdirSync(dir).filter((f) => /^\d{14}_/.test(f)).sort().at(-1).slice(0, 14)
const t = new Date(Date.UTC(+latest.slice(0, 4), +latest.slice(4, 6) - 1, +latest.slice(6, 8), +latest.slice(8, 10), +latest.slice(10, 12), +latest.slice(12, 14) + 1))
const stamp = t.toISOString().replace(/[-:T]/g, '').slice(0, 14)
writeFileSync(`${dir}/${stamp}_island_items.sql`, sql)
console.log(`${items.length} items (${locked.length} level-locked) -> ${stamp}_island_items.sql`)
