"""
Lists every harvest node on every map for the server (so only real nodes can be harvested) and writes it as a
migration. Run after editing a map's harvest nodes:

    python scripts/gen-nodes.py
"""
import re
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAPS = ['greenhaven', 'science_island', 'mathematics_mountains', 'technology_city', 'language_kingdom']
MATERIAL = {'harvest_tree': 'wood', 'harvest_rock': 'stone', 'herb': 'herbs', 'crystal': 'crystal'}

rows_sql = []
for place in MAPS:
    src = (ROOT / 'src' / 'game' / 'maps' / f'{place}.ts').read_text(encoding='utf8')
    rows = re.findall(r"^\s*'([^']{30,})',?\s*$", src, re.M)
    legend = {}
    for m in re.finditer(r"^\s*(?:'(.)'|(\w)):\s*\{([^}]*)\}", src, re.M):
        prop = re.search(r"prop: '(\w+)'", m.group(3))
        if prop and prop.group(1) in MATERIAL:
            legend[m.group(1) or m.group(2)] = prop.group(1)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in legend:
                rows_sql.append(f"  ('{place}', {x}, {y}, '{legend[ch]}', '{MATERIAL[legend[ch]]}')")

migrations = ROOT / 'supabase' / 'migrations'
latest = max(f.name.split('_')[0] for f in migrations.iterdir() if re.match(r'^\d{14}_', f.name))
stamp = max(datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S'), str(int(latest) + 1))
out = migrations / f'{stamp}_harvest_nodes.sql'
out.write_text(
    '-- GENERATED by scripts/gen-nodes.py from src/game/maps. Do not edit by hand.\n'
    'delete from public.harvest_nodes;\n'
    'insert into public.harvest_nodes (place, x, y, kind, material) values\n' + ',\n'.join(rows_sql) + ';\n',
    encoding='utf8', newline='\n')
print(len(rows_sql), 'nodes ->', out.relative_to(ROOT))
